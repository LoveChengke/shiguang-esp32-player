"""Reproduce the original, 440Hz diagnostic MP3 (requires lameenc==1.8.1)."""
import math
import pathlib
import struct
import lameenc

ROOT = pathlib.Path(__file__).resolve().parents[1]

def main():
    encoder = lameenc.Encoder()
    encoder.set_bit_rate(64)
    encoder.set_in_sample_rate(22050)
    encoder.set_channels(1)
    encoder.set_quality(2)
    pcm = b"".join(struct.pack("<h", int(5000 * math.sin(2 * math.pi * 440 * n / 22050))) for n in range(11025))
    data = encoder.encode(pcm) + encoder.flush()
    folder = ROOT / "sdcard" / "music"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "test-tone.mp3").write_bytes(data)
    lines = [", ".join("0x%02x" % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    (ROOT / "include" / "diagnostic_tone.hpp").write_text(
        "// Generated by tools/generate_tone.py; original 440Hz sine wave.\n#pragma once\n"
        "#include <Arduino.h>\nstatic const uint8_t diagnosticTone[] PROGMEM = {\n" + ",\n".join(lines) + "\n};\n", encoding="utf-8")
    print("Generated", len(data), "MP3 bytes")

if __name__ == "__main__":
    main()
